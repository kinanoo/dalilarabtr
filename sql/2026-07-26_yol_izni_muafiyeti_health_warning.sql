<h3>وماذا عند انتهاء العمل؟</h3>
<p>ينصّ القانون على مدّتَي استمرار: <strong>عشرة أيام</strong> في كل الأحوال من تاريخ انتهاء التأمين الإجباري؛ وترتفع إلى <strong>تسعين يوماً</strong> لمن كان له 90 يوم اشتراك إجباري خلال السنة السابقة — وتشمل من يعولهم.</p>
<p>وبعد انقضاء هذه المدة لا يوجد باب عودة داخل الضمان: البدائل المتاحة في القانون مقصورة نصّاً على <strong>المواطنين</strong>، والبند الذي يشمل الحماية الدولية <strong>لا يشمل الحماية المؤقتة</strong>، والبند الذي يشترط الإقامة مغلق لأن <strong>إذن العمل لا يحلّ محلّ الإقامة</strong> بنصّ المادة 29/5 من لائحة الحماية المؤقتة.</p>

<h3>إسناد رسمي يسمّي هذه الفئة صراحةً</h3>
<p>ورد في تعميم رسمي (AFAD رقم 2015/8، البند 12) نصّ يفرّق بين المشمولين بالحماية المؤقتة عموماً و<strong>من دخلوا نطاق الضمان بحصولهم على إذن عمل</strong>: فحصة المساهمة عن الوصفات لا تُؤخذ من الأولين، <strong>باستثناء</strong> الثانين. أي أن التمييز الإداري بين الحالتين موجود في النصوص، لا في الروايات فقط.</p>

<h3>وماذا عن «التقرير الطبي» لإعادة العلاج المجاني؟</h3>
<p>نقولها بأمانة: <strong>لم نجد إجراءً رسمياً منشوراً</strong> اسمه إعادة تفعيل الحق الصحي، ولا نصّاً يربط التقرير الطبي بذلك. ما هو موثَّق رسمياً شيء مختلف: من يُثبَت عجزه عن الدفع تُردّ إليه حصص المساهمة التي دفعها، بطلب لدى <strong>وقف التضامن والتكافل الاجتماعي</strong> في ولايته، بعد تقدير من وزارة الأسرة والخدمات الاجتماعية بالتنسيق مع إدارة الهجرة.</p>
<p>ويتداول كثيرون أن تقديم تقرير طبي إلى مديرية الهجرة يساعد في إعادة تفعيل الاستحقاق لمن يحتاج علاجاً مستمراً. <strong>هذه ممارسة إدارية يرويها الناس ولا نستطيع إسنادها إلى نصّ منشور</strong> — قد تجري في بعض الولايات بتعليمات داخلية. فإن كنت في هذا الوضع، راجع مديرية الهجرة في ولايتك ومعك تقاريرك الطبية، واسأل عن إعادة تقييم وضعك.</p>

