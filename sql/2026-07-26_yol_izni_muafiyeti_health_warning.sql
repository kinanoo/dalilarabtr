<h2>ما هي وثيقة إعفاء إذن الطريق فعلاً</h2>
<p>منذ سنوات كان المشمول بالحماية المؤقتة يحتاج <strong>إذن طريق</strong> منفصلاً لكل رحلة بين الولايات، قصير المدة ولوجهة محدَّدة. والجديد أن ظهرت وثيقة باسم <strong>«Yol İzni Muafiyeti»</strong> — إعفاء من إذن الطريق.</p>
<p>وقد اطّلعنا على <strong>نموذجها الرسمي</strong> المرفق بتعميم منقول عن إدارة الهجرة، وهذا ما يحمله:</p>
<ul>
<li><strong>مدّة</strong> ممتدة سنة كاملة بين تاريخَين مدوَّنَين على الوثيقة نفسها.</li>
<li><strong>حقل «İL MUAFİYETİ VAR»</strong> أي أن قيد الولاية الواحدة مرفوع.</li>
<li><strong>نصّ صريح:</strong> «يمنح الأجنبي المشمول بالحماية المؤقتة في ولايتنا… إعفاءً من قيود السفر داخل تركيا خلال المدة المحدَّدة».</li>
</ul>
<p><strong>لكن انتبه إلى دقّة مهمة:</strong> الصلاحية هي «بين التاريخين المدوَّنين على الوثيقة» — فالسنة الكاملة هي ما ظهر في النموذج، لا قاعدة مضمونة لكل وثيقة.</p>

<h2>مَن يستحقّه؟ — ما نعرفه وما لا نعرفه</h2>
<p><strong>لا يوجد مصدر رسمي منشور يسمّي الفئات المؤهَّلة.</strong> التعميم يشير إلى «المجموعات المحدَّدة» دون أن يعدّدها.</p>
<p>وما يتداوله المستفيدون — <strong>وننقله بوصفه تجربة مجتمعية لا قاعدة رسمية</strong> — أن الموافقات صدرت لطلاب الجامعات، ولحاملي إذن العمل، ولحاملي إعفاء إذن العمل، وللمتزوّجين من مواطنين أتراك. ومن هم خارج هذه الفئات يستطيعون التقديم، لكن القبول غير مضمون.</p>
<p><strong>وهذا يعني أمراً عملياً مهماً:</strong> لا تستخرج إذن عمل <strong>لمجرّد</strong> الحصول على إعفاء إذن الطريق. فالاشتراط غير مثبت رسمياً، والثمن الصحّي المحتمل مثبت بنصّ القانون.</p>

<h2>تصحيح مهم: «إعفاء إذن العمل» ليس ما يظنّه كثيرون</h2>
<p>يخلط كثيرون بين إذن العمل و«إعفاء إذن العمل». وبنصّ لائحة عمل المشمولين بالحماية المؤقتة (الصادرة عام 2016)، فإن الإعفاء مقصور على <strong>أعمال الزراعة الموسمية وتربية الحيوانات فقط</strong> — والاستمارة نفسها تحمل هذا القيد. ويُقدَّم لولاية التسجيل، ومدّته سنة كحدّ أقصى، وثلاثة أشهر إن كان العمل خارج ولاية تسجيلك.</p>
<p>أي أنه <strong>ليس إعفاءً عاماً</strong> يتيح لك أي عمل، <strong>ولا يمنحك بذاته تنقّلاً حرّاً سنة كاملة</strong>.</p>

