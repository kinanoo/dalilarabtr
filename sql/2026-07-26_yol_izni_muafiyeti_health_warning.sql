<h2>⚠️ الثمن الصحّي: لماذا قد يتوقّف علاجك المجاني</h2>
<p>هذه أهمّ فقرة في الصفحة، ونذكرها أولاً لأن كثيرين يكتشفونها بعد فوات الأوان.</p>
<p>حين تحصل على <strong>إذن عمل</strong> ويسجّلك صاحب العمل في مؤسسة الضمان الاجتماعي، فأنت — بنصّ <strong>المادة 60/1(أ) من قانون الضمان الاجتماعي رقم 5510</strong> — تصير <strong>مؤمَّناً صحياً عاماً</strong>. ولا يوجد استثناء للأجانب في هذا البند؛ الاستثناء الوحيد في المادة يخصّ حاملي الإقامة أقلّ من سنة، لا الموظفين.</p>
<p>وهنا تقع المشكلة. تنصّ <strong>المادة 67/1(أ)</strong> من القانون نفسه على أنه يُشترط للانتفاع بالخدمة الصحية أن يكون للمؤمَّن <strong>ثلاثون يوم اشتراك خلال السنة الأخيرة</strong>. والموظفون <strong>غير مستثنَين</strong> من هذا الشرط. والاستثناء الوحيد منه يخصّ من كان <strong>مُعالاً</strong> لدى مؤمَّن آخر ثم خرج من تلك الصفة — وحامل الكملك لم يكن كذلك.</p>
<p><strong>والنتيجة العملية:</strong> من يبدأ العمل يبدأ برصيد <strong>صفر</strong> من الثلاثين يوماً المطلوبة، فقد تفشل أهليّته الصحية حتى تتراكم. وهذه هي الفجوة التي يرويها كثيرون بعبارة «انقطع علاجي بعد ما طلّعت إذن عمل».</p>

