DECLARE
  canon_count integer;
  thin_count integer;
  draft_count integer;
  new_identity_count integer;
BEGIN
  SELECT count(*) INTO canon_count
  FROM articles
  WHERE slug IN (
    'identity-kimlik-iptal-v160',
    'vergi-numarasi-tax-number-foreigners',
    'gss-premium-2026-foreigners-syrians',
    'syria-temporary-protection-health-2026',
    'tourist-residence-first-application-turkey-2026',
    'high-school-equivalency-turkey-2026'
  ) AND status = 'approved' AND active = true;

  SELECT count(*) INTO thin_count
  FROM articles
  WHERE slug IN (
    'identity-kimlik-iptal-v160',
    'vergi-numarasi-tax-number-foreigners',
    'gss-premium-2026-foreigners-syrians',
    'syria-temporary-protection-health-2026',
    'tourist-residence-first-application-turkey-2026',
    'high-school-equivalency-turkey-2026'
  ) AND length(regexp_replace(coalesce(details, ''), '<[^>]+>', ' ', 'g')) < 1500;

  SELECT count(*) INTO draft_count
  FROM articles
  WHERE slug IN (
    'tenant-rights-rent-increase-cap',
    'rent-contract-tenant-rights-turkey-2026'
  ) AND status = 'draft';

  SELECT count(*) INTO new_identity_count
  FROM articles
  WHERE slug IN ('tourist-residence-first-application-turkey-2026', 'high-school-equivalency-turkey-2026')
    AND id = slug;

  IF canon_count <> 6 THEN
    RAISE EXCEPTION 'FAILED: expected 6 approved rebuilt/new pages, found %', canon_count;
  END IF;
  IF thin_count <> 0 THEN
    RAISE EXCEPTION 'FAILED: % rebuilt pages remain under 1,500 visible characters', thin_count;
  END IF;
  IF draft_count <> 2 THEN
    RAISE EXCEPTION 'FAILED: expected 2 retired housing drafts, found %', draft_count;
  END IF;
  IF new_identity_count <> 2 THEN
    RAISE EXCEPTION 'FAILED: new page id/slug invariant failed (found %)', new_identity_count;
  END IF;

  RAISE NOTICE 'OK: 6 rebuilt/new pages approved, no thin page, 2 housing duplicates drafted, new id=slug checks passed.';
END
$check$;

COMMIT;

