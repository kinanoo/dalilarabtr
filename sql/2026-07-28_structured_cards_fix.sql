       (array_to_string(tips,'|')      LIKE '%444 4 868%')::int          AS unverified_phone,
       (array_to_string(steps,'|')     LIKE '%لا يحق للشرطة منعك%')::int AS consul_overclaim,
       coalesce(array_length(documents,1),0) AS docs,
       coalesce(array_length(steps,1),0)     AS steps_n,
       coalesce(array_length(tips,1),0)      AS tips_n
FROM articles
WHERE slug IN ('lost-kimlik-replacement','kimlik-renewal-steps','deportation-rights',
               'detention-center-rights','police-station-rights')
ORDER BY slug;
