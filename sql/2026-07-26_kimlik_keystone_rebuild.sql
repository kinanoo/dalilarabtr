  details = $html$<h2>ما هو الكملك؟ بعبارة واحدة</h2>
<p>«الكملك» (بالتركية <em>kimlik</em>، أي الهوية) هو الاسم الدارج لـ<strong>بطاقة الحماية المؤقتة</strong> (Geçici Koruma Kimlik Belgesi). وهي وثيقة تُصدرها رئاسة إدارة الهجرة التركية للسوريين، وتحمل صورتك وبياناتك و<strong>رقم أجنبي من 11 خانة يبدأ بـ99</strong>.</p>
<p>وأساسها القانوني <strong>المادة 91 من قانون الأجانب والحماية الدولية رقم 6458</strong>، ولائحة الحماية المؤقتة الصادرة عام 2014 برقم 2014/6883. والتعريف الرسمي للمشمول بها كما تنشره إدارة الهجرة: «الشخص الذي اضطر إلى ترك بلده، والذي هو غير قادر بالرجوع إلى بلده الذي غادره، وتوجّه إلى حدودنا ضمن تدفّقات جماعية».</p>
<p><strong>ملاحظة تمنع خلطاً شائعاً:</strong> الرقم الذي يبدأ بـ99 ليس خاصاً بحملة الكملك وحدهم — فهو صيغة رقم الأجنبي في تركيا عموماً. الذي يحدّد وضعك هو <strong>نوع الوثيقة</strong> لا بادئة الرقم.</p>

<h2>الفرق بين الكملك والإقامة — أهم فقرة في هذه الصفحة</h2>
<p>هذا ليس فرقاً شكلياً في اسم الورقة، بل فرق في القانون الذي تخضع له، وتترتّب عليه نتائج تمسّ حياتك:</p>
<ul>
<li><strong>الكملك (حماية مؤقتة):</strong> يمنحك حق البقاء والحماية من الإعادة القسرية، لكن حامله <strong>لا يُعدّ مقيماً أجنبياً</strong> وفق قانون الإقامة، وحركته داخل تركيا وخارجها مقيّدة.</li>
<li><strong>الإقامة (ikamet):</strong> تُمنح ضمن قانون الأجانب والحماية الدولية بأنواعها (سياحية، عائلية، عمل، دراسة، مستثمر)، وصاحبها يتمتّع بمرونة أكبر في الدخول والخروج.</li>
</ul>
<p>وهذه أمثلة عملية على الفرق، كلها موثَّقة في صفحات أخرى على موقعنا:</p>
<ul>
<li><strong>العبور البرّي إلى سوريا:</strong> منذ 1 كانون الثاني/يناير 2026 يستطيع حامل <strong>الإقامة</strong> أو إذن عمل مستقلّ عن الحماية المؤقتة الدخول إلى سوريا والعودة عبر المعابر. و<strong>حامل الكملك غير مشمول</strong> — حتى لو كان لديه إذن عمل على الكملك. <a href="/article/syria-turkey-border-crossings-2026">التفاصيل والفئات كاملة</a>.</li>
<li><strong>العودة إلى سوريا:</strong> بابك الوحيد هو «العودة الطوعية»، وهي تُنهي صفتك وتُسحب بطاقتك — <a href="/article/voluntary-return-syria-procedure-2026">وهي عملياً باب باتجاه واحد</a>.</li>
<li><strong>التنقل بين الولايات:</strong> عليك إذن طريق مسبق (تفصيله أدناه)، وهذا لا يُطلب من حامل الإقامة.</li>
</ul>
<p><strong>وانتبه جيداً:</strong> تنصّ إدارة الهجرة على أن بطاقة الحماية المؤقتة <strong>لا تمنح حق الانتقال إلى إذن إقامة</strong>، وأن الحصول على إذن إقامة <strong>يُنهي</strong> الحماية المؤقتة. فمن يعرض عليك «تحويل الكملك إلى إقامة» مقابل مال يبيعك إجراءً غير موجود.</p>

<h2>هل صحيح أن تركيا ستُنهي الحماية المؤقتة؟</h2>
<p>يتكرّر هذا السؤال ويقوم على شائعة، ونقولها بوضوح: <strong>حتى 26 تموز/يوليو 2026 لا يوجد أي قرار بإنهاء الحماية المؤقتة.</strong></p>
<p>تنصّ المفوضية السامية للأمم المتحدة لشؤون اللاجئين في تركيا صراحةً على أن السلطات التركية لم تُعلن أي قرار برفع النظام. وإنهاؤه — بحسب اللائحة نفسها — لا يكون إلا بقرار من رئيس الجمهورية يُنشر في الجريدة الرسمية، ولم يصدر مثل هذا القرار.</p>
<p>أمّا ما يُتداول عن «مهلة سنتين» أو «تحويل الكملك إلى إقامة سياحية» فلا سند له: أصل الرواية تقارير تنقل عن «مصادر أمنية» غير مسمّاة، <strong>ولا تذكر أي سنة ولا تذكر الإقامة السياحية إطلاقاً</strong> — هذه التفاصيل أُضيفت في التداول لا في الأصل. ولا تتّخذ قراراً مصيرياً — بيع بيت، ترك عمل، عودة — بناءً على منشور.</p>

<h2>حقوقك بموجب الحماية المؤقتة</h2>
<p>تتلخّص فيما تذكره المفوضية: <strong>حق البقاء في تركيا</strong> إلى حين إيجاد حلّ أكثر ديمومة، و<strong>الحماية من الإعادة القسرية</strong> إلى سوريا، والوصول إلى <strong>الصحة والتعليم والمساعدة الاجتماعية والدعم النفسي وخدمات الترجمة وسوق العمل</strong>.</p>
<p>والتعليم في المدارس الحكومية متاح، والوصول إلى العمل يمرّ عبر مسار خاص نشرحه أدناه.</p>

<h2>ما تغيّر فعلياً في التغطية الصحية منذ 2026</h2>
<p>هذا تغيير حقيقي وصادر، وليس شائعة — لكن ما يُتداول عنه فيه خطأ مكلف.</p>
<p><strong>ما صدر:</strong> عُدّلت المادة 27 من لائحة الحماية المؤقتة بقرار رئاسي رقم <strong>10658</strong>، نُشر في <strong>الجريدة الرسمية التركية بتاريخ 28 تشرين الثاني/نوفمبر 2025، العدد 33091</strong>، وبدأ سريانه في <strong>1 كانون الثاني/يناير 2026</strong>. ومقتضاه أن المشمولين بالحماية المؤقتة صاروا يدفعون <strong>«حصة المساهمة»</strong> (katılım payı) نفسها التي يدفعها المؤمَّن عليه في تركيا، وفق بلاغ التطبيق الصحي الصادر عن مؤسسة الضمان الاجتماعي.</p>
<p><strong>⚠️ ما لم يصدر — وهذا هو الخطأ المنتشر:</strong> <strong>لا يوجد قسط شهري، ولا يُطلب منك التسجيل في التأمين الصحي العام.</strong> تغطيتك ما زالت قائمة عبر المادة 27. ونصّ القرار الرئاسي <strong>لا يتضمّن أي مبلغ ولا أي قسط</strong>.</p>
<p>أمّا مبلغ <strong>1,981.80 ليرة شهرياً</strong> الذي يتداوله كثيرون فهو موجود فعلاً لكنه <strong>يخصّ فئة أخرى تماماً</strong>: هو قسط التأمين الصحي العام لعام 2026 لمن يتجاوز دخل الفرد في أسرته ثلث الحد الأدنى الإجمالي للأجور، أي 6% من مبلغ 33,030 ليرة. وصفحة مؤسسة الضمان الاجتماعي الخاصة بهذا القسط <strong>لا تذكر الحماية المؤقتة إطلاقاً</strong>. <strong>لا تدفع هذا المبلغ ولا تعتبره ديناً عليك.</strong></p>
<p><strong>كم تدفع فعلياً؟</strong> مبالغ بعشرات الليرات لا بالآلاف، وتختلف بحسب جهة العلاج: لا مساهمة لدى طبيب الأسرة ومراكز الرعاية الأولية، ومبلغ يرتفع تدريجياً في مستشفيات الدولة ثم الجامعات ثم المستشفيات الخاصة، مع تخفيض عند التحويل من طبيب الأسرة، ومساهمة صغيرة على الوصفة الدوائية. وهذه المبالغ <strong>تتغيّر مع كل تعديل لبلاغ التطبيق الصحي</strong> — راجع الرقم الساري لدى مؤسسة الضمان الاجتماعي قبل أن تعتمد عليه.</p>
<p><strong>ما يبقى بلا مقابل</strong> بنصّ المادة المعدَّلة: <strong>اللقاحات</strong> مستثناة صراحةً، وكذلك لقاحات الأطفال والمسوحات الوطنية للوقاية من الإعاقة ومن وفيات الرضّع، وفحوصات الأمراض السارية والوقاية منها، وخدمات الصحة الإنجابية.</p>
<p><strong>إن كان دخلك لا يكفي — الآلية استرداد لا إعفاء مسبق:</strong> تدفع أولاً ثم تتقدّم بطلب استرداد لدى <strong>وقف التضامن والتكافل الاجتماعي</strong> في ولايتك، بعد أن تُثبت وزارة الأسرة والخدمات الاجتماعية بالتنسيق مع إدارة الهجرة عدم قدرتك على الدفع.</p>
<p><strong>والأهمّ عملياً:</strong> تحقّق من <strong>فعالية تغطيتك</strong> قبل التوجّه إلى المستشفى. فمن كانت تغطيته غير فعّالة يُطالَب بـ<strong>التكلفة الكاملة</strong> للمعاينة والعلاج والدواء، لا بحصة المساهمة وحدها. ومن يحتاج علاجاً مستمراً ولا يقدر على الدفع يستطيع طلب إعادة تقييم وضعه لدى مديرية الهجرة في ولايته.</p>
<p><strong>وهذا التعديل إجراء إداري لا يمسّ وضعك القانوني ولا يُنهي بطاقتك.</strong></p>

<h2>إذن الطريق: السفر بين الولايات</h2>
<p>أنت ملزَم بالإقامة في <strong>الولاية المسجَّل فيها</strong>، وللسفر إلى ولاية أخرى عليك الحصول <strong>مسبقاً</strong> على وثيقة <strong>إذن الطريق</strong> (yol izin belgesi) من مديرية الهجرة في ولايتك أو عبر بوابة الحكومة الإلكترونية.</p>
<p>وليس إجراءً شكلياً: تُشترط أسباب معقولة كالعمل أو الدراسة أو العلاج أو صلة القرابة، <strong>والموافقة تقديرية وقد تُرفض</strong> — فلا تشترِ تذاكر قبل صدور الإذن.</p>
<p><strong>وأمّا المدة فلا يوجد سقف موحّد معلن</strong>، خلافاً لما يُتداول: الإذن صالح بين التاريخين المدوَّنين عليه، وتُحدَّد المدة بحسب سبب السفر — وقد وثّقت وزارة العمل والضمان الاجتماعي حالات يُمنح فيها الإذن لمدة تصل إلى ثلاثة أشهر لمن يعمل في الزراعة الموسمية في ولاية أخرى.</p>
<p><strong>تنبيه:</strong> مدة «خمسة عشر يوماً» الشائعة تخصّ إذن الوصول إلى <strong>المعبر الحدودي في حالة العودة الطوعية</strong>، ولا علاقة لها بالتنقل بين الولايات.</p>
<p>والسفر بلا هذه الوثيقة يعرّضك لإجراءات إدارية وللإعادة إلى ولاية تسجيلك، وشركات النقل ملزَمة بعدم بيع التذكرة لمن لا يحملها.</p>

<h2>العمل: إذن العمل والإعفاء منه</h2>
<p>في <strong>26 حزيران/يونيو 2026</strong> أعلن وزير الداخلية التركي إلغاء إلزامية الحصول على إذن العمل للمشمولين بالحماية المؤقتة والاستعاضة عنها بنظام <strong>«الإعفاء من إذن العمل»</strong>.</p>
<p><strong>لكن انتبه إلى الفرق بين إعلان وقرار نافذ:</strong> حتى تاريخ تحديث هذه الصفحة لم يصدر في الجريدة الرسمية نصّ تنفيذي، ولائحة 2016 الناظمة لعمل المشمولين بالحماية المؤقتة ما تزال سارية.</p>
<p><strong>وعملياً — وهذه النقطة التي تحمي وضعك:</strong> الإعفاء <strong>لا يُمنح تلقائياً</strong>. عليك استخراج <strong>وثيقة الإعفاء</strong>، وعلى صاحب العمل تسجيلك في مؤسسة الضمان الاجتماعي قبل بدء العمل. والعمل بلا وثيقة يبقى مخالفة تُوقع <strong>غرامات عليك وعلى صاحب العمل معاً</strong>. ولا تصدّق من يَعِدك بـ«إعفاء فوري ومجاني» مقابل مال — الوثيقة خاضعة لرسم مقرَّر.</p>

