-- ─── 2) سطر في الشريط الإخباري ───────────────────────────────────────────────
INSERT INTO news_ticker (text, link, priority, is_active)
SELECT
  $$تحقّق: لا قرار تركياً يسمح بإدخال سيارات السوريين «مجاناً» — والمؤكّد شروط صارمة لفئتين فقط$$,
  '/updates/' || u.id::text,
  1,
  true
FROM updates u
WHERE u.title ILIKE '%دخول سيارات السوريين إلى تركيا%'
  AND NOT EXISTS (
    SELECT 1 FROM news_ticker n WHERE n.text ILIKE '%إدخال سيارات السوريين%'
  )
ORDER BY u.created_at DESC
LIMIT 1;


-- ─── 3) تحقّق ───────────────────────────────────────────────────────────────
