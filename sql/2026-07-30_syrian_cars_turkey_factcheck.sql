INSERT INTO updates (title, type, category, content, summary, date, link, source_name, source_url, active)
SELECT * FROM (VALUES
  (
    $$هل صار دخول سيارات السوريين إلى تركيا «مجانياً وبلا رسوم»؟ لا قرار تركياً معلناً — وهذه هي الحقيقة الكاملة$$,
    $$alert$$,
    $$general$$,
    $$ينتشر على وسائل التواصل منشور يقول إن السوريين أصحاب الإقامات في تركيا والمجنّسين صار بإمكانهم إدخال سياراتهم واستعمالها داخل تركيا مجاناً وبلا أية رسوم عبر معبر باب الهوى. دقّقنا الادّعاء من مصادره، وهذه هي النتيجة.

أولاً: لا يوجد أي قرار تركي رسمي منشور بهذا المعنى حتى تاريخه. موقع معبر باب الهوى الرسمي لا يحمل قراراً كهذا، والهيئة العامة للمنافذ البرية والبحرية السورية نفسها نفت — على لسان مدير علاقاتها مازن علوش — صحة ما نُشر سابقاً عن السماح بدخول السيارات السورية إلى تركيا، وأكدت أن القرار لم يدخل حيّز التنفيذ وأن أي إجراء رسمي أو موعد للتطبيق يُعلن عبر القنوات الرسمية.

ثانياً: ما تناقلته تقارير صحفية في أيار 2026 عن حالات دخول جرت فعلاً عبر باب الهوى يخصّ فئتين فقط لا علاقة لهما بعموم أصحاب الإقامات: حاملي الجنسية التركية، وأصحاب أذون العمل النظامية. وحتى هؤلاء بشروط صارمة: إثبات إقامة 180 يوماً على الأقل خارج تركيا يُتحقّق منه عبر e-Devlet، وخلوّ الذمة من الديون والمخالفات داخل تركيا، وتأمين تركي (سيغورتا) للسيارة، وترجمة رخصة السيارة وأوراقها إلى التركية، ورسم دخول في الجانب السوري. أي أن الإجراء — حيث طُبّق — ليس مجانياً وليس مفتوحاً للمقيمين.

ثالثاً: الاتجاه الرسمي التركي هذه الأيام تشديدٌ لا إعفاء: في الجريدة الرسمية التركية الصادرة أمس (29 تموز 2026، العدد 33324) لائحة جديدة تُلزم السيارات ذات اللوحات الأجنبية بالتسجيل في أنظمة تحصيل رسوم الطرق، وتقضي بفحص ديون رسوم العبور والغرامات عند المنافذ الحدودية، ومنع خروج السيارة من تركيا قبل سدادها.

