FROM updates WHERE title ILIKE '%دخول سيارات السوريين إلى تركيا%'
UNION ALL
SELECT 'ticker', text, is_active::text, link
FROM news_ticker WHERE text ILIKE '%إدخال سيارات السوريين%';
