<h2>مهلة تبليغ تغيير العنوان: عشرون يوم عمل — لا شهر ونصف</h2>
<p>هذه أكثر نقطة يقع فيها الخطأ. القانون رقم 5490 (قانون خدمات النفوس) يلزم بتبليغ تغيير مكان الإقامة خلال <strong>عشرين يوم عمل</strong> («yirmi iş günü içinde»)، والنص يشمل الأجانب صراحةً: «yabancılar, yerleşim yeri adreslerine ilişkin değişiklikleri yirmi iş günü içinde nüfus müdürlüğüne bildirirler».</p>
<p>انتبه إلى «يوم <em>عمل</em>»: العطل الرسمية وأيام نهاية الأسبوع لا تُحسب، لكن لا تبنِ على ذلك — المهلة أقصر مما تظن بكثير إن قست بالتقويم. ومَن لم يبلّغ في المهلة تُطبَّق عليه <strong>غرامة إدارية</strong> بموجب المادة 68/1-ج من القانون نفسه.</p>
<p>للتفاصيل الكاملة عن حملة تحديث العنوان الإجباري وعواقب التخلّف عنها، راجع: <a href="/article/syrian-address-update-mandate-turkey">تحديث العنوان الإجباري للسوريين — العواقب وطريقة التحديث</a>.</p>

