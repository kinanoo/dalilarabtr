<ul>
<li><strong>تغيير السكن</strong> — وهو الحالة الأكثر شيوعاً، وعليها تسري مهلة العشرين يوم عمل.</li>
<li><strong>مولود جديد</strong> يُضاف إلى القيد.</li>
<li><strong>تغيّر الحالة الاجتماعية</strong> (زواج أو طلاق).</li>
<li><strong>تجديد جواز السفر</strong> أو تغيّر رقمه.</li>
<li><strong>تصحيح خطأ</strong> في الاسم أو تاريخ الميلاد أو أي بيان في القيد.</li>
<li><strong>طلب مراجعة</strong> يصلك من إدارة الهجرة عبر رسالة نصية أو ورقة رسمية.</li>
</ul>

<h2>البصمة والصورة: متى تُطلب؟</h2>
<p>في كثير من مراجعات التحديث تُؤخذ <strong>البصمات وصورة شخصية محدَّثة</strong> ضمن الموعد نفسه، خصوصاً عند تجديد البطاقة أو بعد مرور مدة طويلة على آخر تسجيل. هذا يعني أمرين عمليين: حضور صاحب الشأن شخصياً لا يُغني عنه وكيل، وحضور كل فرد من العائلة إن كان التحديث يشمله.</p>

<h2>أخطاء تُبطل الموعد أو تؤخّر الملف</h2>
<ul>
<li><strong>وثيقة عنوان باسم شخص آخر:</strong> عقد الإيجار أو الفاتورة يجب أن يكون باسمك، أو مرفقاً بما يثبت العلاقة بصاحب الاسم.</li>
<li><strong>نقص النمرتاج</strong> (numarataj) حيث تطلبه الولاية — وهو وثيقة ترقيم العنوان من البلدية، ومطلوبة في إسطنبول تحديداً.</li>
<li><strong>الحضور بلا أصل الوثائق:</strong> النسخ وحدها لا تكفي؛ اصطحب الأصل والنسخة معاً.</li>
<li><strong>تجاهل رسالة المراجعة:</strong> إن وصلتك رسالة نصية بطلب استكمال، لها مهلة محدّدة — تجاوزها يعيدك إلى نقطة الصفر.</li>
</ul>

