-- تصحيح حقل «التنبيه» (warning)
-- ===========================================================================
-- حقل warning يُرسم صندوقاً أحمر ظاهراً فوق نصّ المقال، ولم يُدقَّق في أي من
-- جولات التحقّق الخمس — لأن التدقيق كان يقرأ details وحده.
--
-- أخطرها في detention-center-rights:
--   «الاحتجاز بدون قرار قضائي أكثر من 48 ساعة = غير قانوني»
--
--   هذا يناقض نصّ القانون في الموضوع الذي بُني المقال كلّه على تصحيحه:
--   الحجز الإداري يصدر بقرار من الولاية لا من قاضٍ (المادة 57/2 من القانون
--   6458)، ولا يتجاوز ستة أشهر قابلة للتمديد ستة أخرى بقرار الولاية أيضاً
--   (المادة 57/3). أما «ثمان وأربعون ساعة» في النصّ فهي مهلتان تُلزمان
--   الإدارة لا تُحرّر المحتجَز: مهلة اتخاذ القرار (المادة 57/1)، ومهلة نقل
--   المحتجَز إلى مركز الترحيل (المادة 57/2).
--
--   أثر الخطأ عملي: محتجَز يقرأ هذا التحذير يظنّ أن حجزه الممتدّ شهوراً
--   «غير قانوني تلقائياً» فينتظر إفراجاً لا يأتي، بدل أن يرفع الاعتراض
--   أمام قاضي الصلح الجزائي (المادة 57/6) ويحفظ مهلة السبعة أيام
--   الخاصة بقرار الترحيل (المادة 53/3).
--
-- وفي deportation-rights: «عدم التحرك = ترحيل نهائي» — الصحيح أن فوات
--   السبعة أيام يُغلق طريق المحكمة الإدارية، وهو ما يجب أن يُقال بدقّة.
--
-- شغّله في Supabase → SQL Editor.

UPDATE articles SET
    warning = 'الحجز الإداري يصدر بقرار من الولاية لا من قاضٍ، وقد يمتدّ ستة أشهر (المادة 57/3). لا تنتظر أن ينتهي بمرور ساعات — اعترض أمام قاضي الصلح الجزائي، واحفظ مهلة السبعة أيام الخاصة بقرار الترحيل.',
    last_update = CURRENT_DATE
WHERE slug = 'detention-center-rights';

UPDATE articles SET
    warning = 'لديك سبعة أيام من تاريخ التبليغ للطعن أمام المحكمة الإدارية. فواتها يُغلق هذا الطريق، ولا تُرحَّل ما دامت الدعوى قائمة إلا برضاك أنت.',
    last_update = CURRENT_DATE
WHERE slug = 'deportation-rights';

UPDATE articles SET
    warning = 'بادر بالإبلاغ والاستبدال فوراً: السفر بلا جواز ساري يتطلّب وثيقة بديلة من قنصليتك أو إذن خروج من الإدارة، وليس أمراً تُرتّبه في يوم السفر.',
    last_update = CURRENT_DATE
WHERE slug = 'lost-passport-turkey';

-- ═══════════════════════════════════════════════════════════════════════════
-- التحقّق — يجب أن يرجع العمودان أصفاراً والحقول غير فارغة
SELECT slug,
       (warning LIKE '%48 ساعة%')::int          AS false_48h,
       (warning LIKE '%ترحيل نهائي%')::int      AS final_overclaim,
       length(warning)                          AS warning_len
FROM articles
WHERE slug IN ('detention-center-rights','deportation-rights','lost-passport-turkey',
               'police-station-rights','lost-residence-card')
ORDER BY slug;
