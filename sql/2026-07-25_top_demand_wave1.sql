<li><strong>تناقض التواريخ</strong> بين الحجوزات والتقرير الطبي وخطة العلاج — أكثر سبب تقني للرفض.</li>
<li><strong>وثيقة دعوة غير موثّقة</strong> أو من جهة لا يمكن التحقّق منها.</li>
<li><strong>القاصرون:</strong> قد تُطلب موافقات موثّقة من وليّ الأمر بحسب الحالة وبلد التقديم — جهّزها مسبقاً لا في يوم الموعد.</li>
