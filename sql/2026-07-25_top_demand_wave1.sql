<h2>ما الذي يقوّي الملف الطبي تحديداً؟</h2>
<p>ملف العلاج يُقيَّم على محورين: <strong>صدق الغرض الطبي</strong> و<strong>اتساق خطة السفر معه</strong>. والذي يصنع الفارق:</p>
<ul>
<li><strong>تقرير طبي واضح</strong> يذكر التشخيص والحاجة إلى العلاج في تركيا تحديداً — لا تقرير عام.</li>
<li><strong>موعد أو خطة علاج من المستشفى</strong> في تركيا بتواريخ محدّدة. هذا أقوى مستند في الملف كله لأنه يربط الغرض بالمدة.</li>
<li><strong>مدة إقامة مطابقة للخطة الطبية:</strong> إن كانت الخطة ثلاثة أسابيع فلا تطلب ثلاثة أشهر. عدم التطابق يقرأه الموظف كغرض آخر متخفٍّ.</li>
<li><strong>إثبات مالي يغطّي العلاج والإقامة معاً</strong> — لا الإقامة وحدها. تكلفة العلاج جزء من المبلغ المتوقع.</li>
<li><strong>المرافق:</strong> إن كان معك مرافق، يجب أن يكون ملفه مرتبطاً بملفك ومبرَّراً بحالتك الطبية، لا ملفاً سياحياً منفصلاً.</li>
</ul>

