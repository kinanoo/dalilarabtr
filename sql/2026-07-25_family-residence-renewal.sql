<h2>تجديد الإقامة العائلية (Uzatma): متى وكيف</h2>
<p>التجديد ليس معاملة جديدة من الصفر، لكنه يسقط لسبب واحد متكرّر: التأخّر. القاعدة الرسمية واضحة — تُقدَّم طلبات التمديد <strong>خلال آخر 60 يوماً قبل انتهاء الإقامة</strong> («altmış gün kalmasından itibaren»)، و<strong>قبل انتهائها في كل الأحوال</strong> («her koşulda ikamet izni süresi dolmadan önce»). أي أن يوماً واحداً بعد تاريخ الانتهاء يعني أنك لم تعد صاحب طلب تمديد، بل صاحب وضع مخالف.</p>

<h3>الخطوات بالترتيب</h3>
<ol>
<li>افتح نظام <strong>e-ikamet</strong> واختر «طلب تمديد» (Uzatma Başvurusu) — التقديم إلكتروني، ولا يبدأ قبل دخولك آخر 60 يوماً.</li>
<li>عبّئ الطلب لكل فرد من العائلة على حدة (الزوج/الزوجة وكل طفل).</li>
<li>بعد إتمام الطلب يُصدر النظام تلقائياً <strong>وثيقة طلب الإقامة</strong> («İkamet İzni Müracaat Belgesi») — احتفظ بها، فهي إثبات أنك ضمن المهلة.</li>
<li>ادفع الرسوم واحتفظ بالإيصال. رمزا الدفع الرسميان: <strong>9207</strong> لبدل البطاقة (Kart Bedeli) و<strong>9233</strong> لرسم الإقامة (İkamet Harcı).</li>
