<h3>هل يمكنك السفر وطلبك قيد الدراسة؟</h3>
<p>نعم، ضمن حدّ محدّد: بوثيقة الطلب مع إيصال الرسوم يمكنك مغادرة تركيا والعودة خلال <strong>15 يوماً</strong>. تجاوز الخمسة عشر يوماً خارج البلاد يعني أن عودتك تخضع لشروط التأشيرة الاعتيادية — وهذه نقطة يجهلها كثيرون فيخسرون معاملتهم بسفرة عائلية.</p>

<h3>شرط الدخل — السبب الأشيع للرفض</h3>
<p>يُشترط في الداعم دخل «لا يقلّ مجموعه عن الحد الأدنى للأجور، وبما لا يقلّ عن ثلث الحد الأدنى لكل فرد من أفراد العائلة» («toplam miktarı asgari ücretten az olmamak üzere ailedeki fert başına asgari ücretin üçte birinden az olmayan gelir»).</p>
<p>بلغة الحساب: تجمع عدد أفراد العائلة (الداعم + المعالين)، وتضرب العدد في ثلث الحد الأدنى، ثم تأخذ <strong>الأكبر</strong> بين هذا الناتج وبين الحد الأدنى كاملاً. مثال توضيحي لعائلة من أربعة أفراد: أربعة أثلاث = حد أدنى وثلث تقريباً. احسب على الحد الأدنى الصافي المعتمد لسنة التقديم، وتحقّق من مديرية الهجرة في ولايتك — التطبيق يختلف بين الولايات في تفاصيل إثبات الدخل.</p>

