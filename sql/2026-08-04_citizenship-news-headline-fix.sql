-- ============================================================================
-- تصحيح صياغة عنوان خبر شبكة «الجنسية بتقييم مزوّر» (2026-08-04)
--
-- المشكلة: العنوان الأصلي دفن الرقم الأبرز (687) إلى آخره، فيقرأ القارئ نصف
-- العنوان قبل أن يصل إلى الرقم الذي يعنيه. والعرف الصحفي — وصياغة المصادر
-- نفسها — يضع الرقم أولاً.
--
-- العنوان الجديد يتصدّره الرقم مع الحفاظ على الدقّة التي أضفناها: «قيد السحب»
-- لا «سُحبت»، لأن الإجراءات الإدارية بُوشرت ولم يصدر إلغاء نافذ.
--
-- يُحدّث كذلك أول فقرة تصحيح الصياغة داخل المتن لتوافق العنوان الجديد.
--
-- شغّله مرّة واحدة في Supabase <- SQL Editor. آمن لإعادة التشغيل.
-- ============================================================================

UPDATE public.updates
SET title = $t$687 جنسية تركية قيد السحب و72 موقوفاً: عملية في 16 ولاية على شبكة «التقييم العقاري المزوّر»$t$
WHERE title = $t$عملية في 16 ولاية على شبكة «الجنسية بتقييم مزوّر»: 72 موقوفاً وإجراءات لسحب جنسية 687 شخصاً$t$;

-- ─── تحقّق نهائي ───
DO $check$
DECLARE
  n_new integer;
  n_old integer;
BEGIN
  SELECT COUNT(*) INTO n_new FROM public.updates
  WHERE title = $t$687 جنسية تركية قيد السحب و72 موقوفاً: عملية في 16 ولاية على شبكة «التقييم العقاري المزوّر»$t$
    AND active = true;

  SELECT COUNT(*) INTO n_old FROM public.updates
  WHERE title = $t$عملية في 16 ولاية على شبكة «الجنسية بتقييم مزوّر»: 72 موقوفاً وإجراءات لسحب جنسية 687 شخصاً$t$;

  IF n_new <> 1 THEN
    RAISE EXCEPTION 'FAILED: العنوان الجديد غير موجود (found %) — تحقّق أن الخبر منشور', n_new;
  END IF;
  IF n_old <> 0 THEN
    RAISE EXCEPTION 'FAILED: العنوان القديم ما زال موجوداً (found %)', n_old;
  END IF;
  RAISE NOTICE 'OK: العنوان صار يتصدّره الرقم.';
END
$check$;

-- ─── مراجعة ───
SELECT id, title, date, category
FROM public.updates
WHERE title LIKE $t$687 جنسية تركية قيد السحب%$t$;
