-- تنبيه رسمي: لا وسطاء للحصول على التأشيرة التركية من سوريا (2026-07-18)
-- ============================================================================
-- المصدر: إعلان سفارة الجمهورية التركية في دمشق (صياغة عامة بأسلوب الموقع).
-- تحقّقنا قبل النشر (2026-07-18):
--   • sy.visafg.com يعمل (HTTP 200) ويعرّف نفسه رسمياً:
--     "Authorized Visa Application Office for Türkiye in Syria".
--   • إعلان السفارة الأصلي (حساب X الرسمي TC_Sam_BE بتاريخ 10.02.2025):
--     طلبات فيزا تركيا من سوريا تُستقبل حصراً عبر "Visa For The Globe".
--   • لا يوجد خبر مكرر في جدول updates (فحص ILIKE على visafg = صفر صفوف).
--   • الرابط الداخلي /article/turkey-visa-from-syria موجود و approved.
--
-- ينشئ: (1) تنبيهاً في صفحة /updates من نوع alert
--        (2) سطراً في الشريط الإخباري يشير لصفحة التنبيه نفسها.
--
-- كيفية التشغيل: Supabase → SQL Editor → New Query → الصق الملف → Run.
-- الملف idempotent — إعادة تشغيله آمنة (لا يُكرّر الصفوف).
-- ============================================================================


-- ─── 1) التنبيه في صفحة التحديثات (/updates) ─────────────────────────────────
INSERT INTO updates (title, type, category, content, summary, date, link, source_name, source_url, active)
SELECT * FROM (VALUES
  (
    $$تنبيه رسمي: لا وسطاء للحصول على الفيزا التركية من سوريا — التقديم حصراً عبر المركز المعتمد$$,
    $$alert$$,
    $$official$$,
    $$حذّرت سفارة الجمهورية التركية في دمشق من تصريحات وادعاءات يروّجها بعض الأفراد والجهات حول قدرتهم على تأمين تأشيرات تركيا أو تسريع معالجة طلباتها. وأكدت أن السلطة الحصرية لإصدار التأشيرات التركية للمقيمين في سوريا هي سفارة الجمهورية التركية في دمشق والقنصلية العامة في حلب، وأن المركز الرسمي الوحيد المخوّل باستقبال الطلبات نيابةً عنهما هو مركز Visa for Globe Syria عبر موقعه الرسمي sy.visafg.com — ولا تُقبل الطلبات إلا من خلاله. وشدّدت السفارة على أن البعثات الدبلوماسية التركية في سوريا لا تتعاون مع أي فرد أو شركة أو منظمة للتوسط في الحصول على التأشيرات ولا تمنح أي تفويض بذلك. لذلك لا تصدّق أي وعود بتأمين فيزا مقابل المال، ولا تسلّم جواز سفرك أو بياناتك أو أموالك لأي جهة غير المركز الرسمي، واستقِ المعلومات الدقيقة والمحدّثة فقط من السفارة في دمشق والقنصلية العامة في حلب والمركز المعتمد. للاطلاع على أنواع التأشيرات المتاحة وخطوات التقديم راجع دليلنا المرتبط بهذا التنبيه.$$,
    $$السلطة الحصرية للفيزا التركية من سوريا: سفارة دمشق وقنصلية حلب، والتقديم فقط عبر المركز الرسمي sy.visafg.com — لا وسطاء ولا مفوّضين.$$,
    $$2026-07-18$$::date,
    $$/article/turkey-visa-from-syria$$,
    $$سفارة الجمهورية التركية في دمشق$$,
    $$https://sy.visafg.com/$$,
    true
  )
) AS v(title, type, category, content, summary, date, link, source_name, source_url, active)
WHERE NOT EXISTS (SELECT 1 FROM updates u WHERE u.content ILIKE '%visafg%');


-- ─── 2) سطر في الشريط الإخباري — يشير لصفحة التنبيه نفسها ────────────────────
INSERT INTO news_ticker (text, link, priority, is_active)
SELECT
  $$تنبيه رسمي: لا وسطاء للفيزا التركية من سوريا — التقديم حصراً عبر المركز المعتمد sy.visafg.com$$,
  '/updates/' || u.id::text,
  1,
  true
FROM updates u
WHERE u.content ILIKE '%visafg%'
  AND NOT EXISTS (
    SELECT 1 FROM news_ticker n
    WHERE n.text ILIKE '%visafg%'
  )
ORDER BY u.created_at DESC
LIMIT 1;


-- ─── 3) تحقّق ───────────────────────────────────────────────────────────────
SELECT 'update' AS kind, title AS ref, active::text AS state, '/updates/' || id::text AS url
FROM updates WHERE content ILIKE '%visafg%'
UNION ALL
SELECT 'ticker', left(text, 50), is_active::text, link
FROM news_ticker WHERE text ILIKE '%visafg%';
-- المتوقع: صفان — update بحالة true، وticker بحالة true ورابطه /updates/<id>.
