-- مفتاح التواصل: إظهار/إخفاء كل طرق الوصول إلى صاحب الموقع
-- ===========================================================================
-- الحاجة: صاحب الموقع لا يريد كتلة «هل الإجراء معقّد؟ راسلنا واتساب» ظاهرة
-- دائماً. أراد مفتاحاً واحداً في لوحة التحكم: حين يُغلقه لا يراها أحد ولا
-- يصل إليه أحد إطلاقاً، وحين يفتحه يضع رقمه فيصلون إليه براحتهم.
--
-- لماذا مفتاح واحد يكفي: كل طرق التواصل في هذا الموقع تنتهي إلى واتساب —
-- كتلة الاستشارة في المقالات والأخبار والأكواد، والزرّ العائم، وزرّ دليل
-- المواقف، وبطاقة صفحة «اتصل بنا»، وحتى نموذج «اطلب خدمة» يفتح wa.me عند
-- الإرسال. فإغلاق واحد يغلق الباب كلّه.
--
-- ما يحدث عند الإغلاق (contact_enabled = false):
--   • كتلة «هل الإجراء معقّد؟» لا تُرسَم أصلاً — لا زرّ معطّل ولا نصّ بديل.
--   • الزرّ العائم يختفي.
--   • زرّ «تواصل معنا عبر واتساب» في دليل المواقف يختفي.
--   • بطاقة واتساب في /contact تختفي.
--   • صفحة /request تعرض إشعاراً صريحاً بأن الطلبات متوقّفة مؤقتاً، وتوجّه
--     الزائر إلى دليل مقدّمي الخدمات — بدل نموذج يجمع طلبات لا تصل.
--   • رقم الهاتف يُحذف من البيانات المهيكلة التي يقرؤها جوجل، فلا يظلّ
--     يعرضه في نتائج البحث.
--   • باقي الموقع — المقالات والأدوات والدليل والأخبار — يعمل كما هو.
--
-- الافتراضي true: القيمة الجديدة لا تُغيّر السلوك الحالي حتى تُغلقه بنفسك.
-- شغّله في Supabase → SQL Editor.

ALTER TABLE site_settings
  ADD COLUMN IF NOT EXISTS contact_enabled boolean NOT NULL DEFAULT true;

COMMENT ON COLUMN site_settings.contact_enabled IS
  'مفتاح رئيسي: عند false تختفي كل طرق التواصل المباشر (كتلة الاستشارة، الزرّ العائم، صفحة اتصل بنا، نموذج طلب الخدمة، ورقم الهاتف في البيانات المهيكلة).';

-- الصفّ المفرد يضمن قيمة صريحة بدل NULL
UPDATE site_settings SET contact_enabled = true WHERE id = 1 AND contact_enabled IS NULL;

