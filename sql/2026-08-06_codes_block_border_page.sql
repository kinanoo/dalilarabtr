-- خطأ في المولّد لا في التحليل. تعديل كان يُفترض أن يكتب بلوك تصحيح الأكواد
-- على صفحتين لم يُطبَّق، فنزل البلوك على صفحة السفر الداخلي (16 قراءة) وحدها
-- ولم ينزل على صفحة المعابر (451 قراءة) — وهي التي كانت تستقبل ادّعاء G-87
-- من الصفحة المدموجة فيها، وهي التي يهبط عليها القارئ فعلاً.
--
-- الادّعاء الخاطئ نفسه زال بحذف الصفحة التي كانت تحمله. الناقص كان التصحيح
-- الإيجابي: أن يقرأ القارئ على الصفحة الأكثر زيارةً ما تعنيه الأكواد فعلاً
-- بحسب جدولنا المدقَّق، بدل أن يُقال له سلفاً أيّ كود سيناله.
--
-- والمولّد أُصلح كي لا يتكرّر: صار يكتب البلوك لكل صفحة في CODES_PAGES.
-- آمن لإعادة التشغيل، ولا يحتاج نشر شيفرة.
-- ============================================================================

UPDATE articles
SET details = coalesce(details, '') || '<div style="margin-top:1.25rem;padding:1rem;border-radius:0.75rem;border:1px solid #fecaca;background:#fef2f2;"><p style="margin:0 0 .5rem 0;"><strong>ما الذي تخاطر به فعلاً:</strong> الخروج من تركيا بلا إذن مسبق من مديرية الهجرة قد يُنهي وضعك تحت الحماية المؤقتة — وهذه هي النتيجة التي تعنيك، لا رمز بعينه.</p><p style="margin:0;"><strong>وعن الأكواد:</strong> تتداول صفحات كثيرة أنّ المخالفة «تضع كودَ كذا». راجعنا جدول الأكواد المدقَّق عندنا (125 كوداً) فوجدنا أنّ <strong>V-160</strong> هو تجميد عنوان لا إبطال بطاقة، وأنّ <strong>G-87</strong> كود أمني لتهديد الأمن العام لا نتيجةَ عبورٍ غير نظامي. فلا تصدّق من يخبرك سلفاً بالكود الذي ستناله — وإن رأيت كوداً على ملفك فابحث عن معناه في <a href="/codes" style="color:#b91c1c;font-weight:bold;">صفحة الأكواد الأمنية ←</a></p></div>',
    last_update = CURRENT_DATE
WHERE slug = 'syria-turkey-border-crossings-2026'
  AND coalesce(details, '') NOT LIKE '%الأكواد المدقَّق%';

-- ═══════════════════════════════════════════════════════════════════════════
-- التحقّق — صفّان، كلاهما true
SELECT slug, (details LIKE '%الأكواد المدقَّق%') AS فيه_تصحيح_الأكواد
FROM articles
WHERE slug IN ('travel-permit', 'syria-turkey-border-crossings-2026')
ORDER BY slug;
