    vals = ("'%s'" % q(a['slug']), "'%s'" % q(a['slug']), "'%s'" % q(a['title']),
            "'%s'" % q(a['intro']), "'%s'" % q(a['details']), arr(a['steps']),
            arr(a['tips']), arr(a['docs']), "'%s'" % q(a['fees']), "'%s'" % q(a['warn']),
            "'%s'" % q(a['source']), arr(a['tags']), "'%s'" % q(CAT), "'approved'",
            "'%s'" % q(a['seo_t']), "'%s'" % q(a['seo_d']), STAMP)
    assert len(vals) == 17
    return ('INSERT INTO articles (' + INSERT_COLS + ')\nVALUES (' + ',\n        '.join(vals) + ')\n'
            'ON CONFLICT (id) DO UPDATE SET\n'
            '    title = EXCLUDED.title, intro = EXCLUDED.intro, details = EXCLUDED.details,\n'
            '    steps = EXCLUDED.steps, tips = EXCLUDED.tips, documents = EXCLUDED.documents,\n'
            '    fees = EXCLUDED.fees, warning = EXCLUDED.warning, source = EXCLUDED.source,\n'
            '    tags = EXCLUDED.tags, category = EXCLUDED.category, status = EXCLUDED.status,\n'
            '    seo_title = EXCLUDED.seo_title, seo_description = EXCLUDED.seo_description,\n'
            '    last_update = EXCLUDED.last_update;\n')


